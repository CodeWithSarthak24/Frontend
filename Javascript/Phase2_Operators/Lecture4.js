// JavaScript Looping Statements

// 1. JavaScript for Loop

console.log("JavaScript for Loop!");

for (let i = 0; i <= 4; i++) {
    console.log(i);
}

// 2. JavaScript while Loop

console.log("JavaScript while Loop!");

let j = 5;
while (j <= 8) {
    console.log(j);
    j++;
}

// 3. JavaScript do...while Loop

console.log("JavaScript do...while Loop!");

let k = 9;
do {
    console.log(k);
    k++
} while (k <= 10);

